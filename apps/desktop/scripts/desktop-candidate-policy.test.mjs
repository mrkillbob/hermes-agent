import assert from 'node:assert/strict'
import { test } from 'vitest'
import { candidateDigest, validateCandidateReceipt } from './desktop-candidate-policy.mjs'

const source = '/candidate/source'
const commit = 'a'.repeat(40)
const target = 'darwin-arm64'
const request = {
  source, work: '/candidate/work', cache: '/candidate/cache',
  commit, tag: null, version: '1.2.3', variant: 'bundled', target,
  bundle_env: {}, channel_request: null, release_epoch: null,
  development_candidate: true
}
const receipt = value => ({ request: value, requestDigest: candidateDigest(value) })
const expected = { source, commit, target }

test('candidate digest matches Python sorted ASCII JSON, including Unicode', () => {
  const value = { z: ['🌱', true, null], a: 'é' }
  // Fixed canonical bytes, not a hash generated by the function under test.
  const canonical = '{"a":"\\u00e9","z":["\\ud83c\\udf31",true,null]}'
  // Keep the independent primitive visible: cross-language receipt identity is the contract.
  return import('node:crypto').then(({ createHash }) => {
    assert.equal(candidateDigest(value), createHash('sha256').update(canonical).digest('hex'))
  })
})

test('a complete candidate receipt admits only its bound source/commit/target', () => {
  assert.deepEqual(validateCandidateReceipt(receipt(request), expected, {}), request)
  assert.equal(validateCandidateReceipt(undefined, expected, {}), null)
})

test.each([
  ['variant', 'light'], ['variant', 'store'], ['target', 'darwin-x64'],
  ['tag', 'v1.2.3'], ['release_commit', 'b'.repeat(40)], ['channel_request', {}], ['release_epoch', 123],
  ['commit', 'b'.repeat(40)], ['source', '/foreign/source'],
  ['development_candidate', false], ['development_candidate', 'true']
])('candidate refuses an internally consistent but unadmitted %s', (key, value) => {
  assert.throws(() => validateCandidateReceipt(receipt({ ...request, [key]: value }), expected, {}), /development candidate/)
})

test.each(['CSC_LINK', 'CSC_NAME', 'CSC_KEY_PASSWORD', 'CSC_KEYCHAIN',
  'APPLE_API_KEY', 'APPLE_NOTARY_PROFILE', 'HERMES_MAC_SIGNATURE_CACHE'])(
  'candidate refuses ambient %s without interpreting its value', key => {
    assert.throws(() => validateCandidateReceipt(receipt(request), expected, { [key]: 'synthetic' }), /development candidate/)
  }
)

test('candidate cannot consume a legacy or tampered request digest', () => {
  assert.throws(() => validateCandidateReceipt({ request }, expected, {}), /development candidate/)
  assert.throws(() => validateCandidateReceipt({ ...receipt(request), request: { ...request, version: '9.9.9' } }, expected, {}), /development candidate/)
})
